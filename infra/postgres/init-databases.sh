#!/bin/sh
set -e

echo "=== Initialising isolated databases for Zero-Dose Tracking Platform ==="

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    -- 1. Create least-privilege service roles
    CREATE ROLE ${CAMPAIGN_DB_USER} WITH LOGIN PASSWORD '${CAMPAIGN_DB_PASSWORD}';
    CREATE ROLE ${TRACKING_DB_USER} WITH LOGIN PASSWORD '${TRACKING_DB_PASSWORD}';
    CREATE ROLE ${KEYCLOAK_DB_USER} WITH LOGIN PASSWORD '${KEYCLOAK_DB_PASSWORD}';

    -- 2. Create isolated databases owned by their respective roles
    CREATE DATABASE ${CAMPAIGN_DB_NAME} OWNER ${CAMPAIGN_DB_USER};
    CREATE DATABASE ${TRACKING_DB_NAME} OWNER ${TRACKING_DB_USER};
    CREATE DATABASE ${KEYCLOAK_DB_NAME} OWNER ${KEYCLOAK_DB_USER};

    -- 3. Enforce strict isolation (block cross-service connections)
    REVOKE CONNECT ON DATABASE ${CAMPAIGN_DB_NAME} FROM PUBLIC;
    REVOKE CONNECT ON DATABASE ${TRACKING_DB_NAME} FROM PUBLIC;
    REVOKE CONNECT ON DATABASE ${KEYCLOAK_DB_NAME} FROM PUBLIC;

    GRANT CONNECT ON DATABASE ${CAMPAIGN_DB_NAME} TO ${CAMPAIGN_DB_USER};
    GRANT CONNECT ON DATABASE ${TRACKING_DB_NAME} TO ${TRACKING_DB_USER};
    GRANT CONNECT ON DATABASE ${KEYCLOAK_DB_NAME} TO ${KEYCLOAK_DB_USER};
EOSQL

echo "=== Database initialisation complete ==="
